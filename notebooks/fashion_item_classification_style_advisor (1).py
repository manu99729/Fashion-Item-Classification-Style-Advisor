def style_advisor(item):

    info = style_knowledge[item]

    response = f"""
## Fashion Item: {item}

### Common Use
{info["use"]}

### Styling Suggestions
"""

    for suggestion in info["styling"]:
        response += f"\n- {suggestion}"

    return response

print(style_advisor("Sneaker"))

def fashion_agent(image):

    # Preprocess image
    image = tf.convert_to_tensor(image)

    # Convert RGB to grayscale if necessary
    if len(image.shape) == 3 and image.shape[-1] == 3:
        image = tf.image.rgb_to_grayscale(image)

    # Resize
    image = tf.image.resize(image, (28, 28))

    # Normalize
    image = tf.cast(image, tf.float32) / 255.0

    # Add batch dimension
    image = tf.expand_dims(image, axis=0)

    # CNN prediction
    predictions = model.predict(image, verbose=0)

    predicted_index = np.argmax(predictions[0])

    item = class_names[predicted_index]

    confidence = predictions[0][predicted_index]

    # Agent
    advice = style_advisor(item)

    result = f"""
# Fashion AI Advisor

**Predicted Item:** {item}

**Confidence:** {confidence * 100:.2f}%

---

{advice}
"""

    return result

